"""大橋2011 表-11 の5件（焼失範囲を地図上に復元し MapInfo で面積と焼失直距離を測ったもの）から、
書かれた幅・長さを使わずに形を出す。

浜田式の比（hamada_shape.py）は 平均幅÷全長 = 面積÷全長²。全長 S1+S3 は出火点→最遠点の直線 D 以上なので、
面積÷D² は浜田式の比の上側の見積もり（仮説に不利な側）になる。
"""
R0 = 0.392
# No: (和暦, 焼失直距離 km, 焼失面積 km², 変災篇の記録の幅÷長さ or None)
OHASHI = {
    73: ("文政6年12月25日 麹町", 2.1, 0.97, None),
    78: ("天保9年4月17日 小田原町", 1.8, 0.88, 0.391),
    85: ("安政2年3月1日 小網町", 1.7, 0.60, 0.308),   # 記録の比は台帳の「安政2年3月2日 小網町」（変災篇の見出しは2日、大橋の表は1日）。11/5 英訳の通読で「—」のままなのを見つけて直した
    87: ("安政5年11月15日 神田相生町", 2.8, 1.98, 0.318),
    88: ("安政6年2月22日 青山", 6.1, 2.80, 0.128),
}
if __name__ == "__main__":
    for no, (name, D, A, rec) in OHASHI.items():
        r = A / D ** 2
        print(f"No{no:<3} {name:22} 面積÷直線² = {r:.3f}  {'<' if r < R0 else '≥'} {R0}   記録の比 {rec if rec else '—'}")
