"""浜田式（1951）の3方向の延焼速度と、焼け跡の形（横÷風下）。

式は藤田隆史 1975「大震火災時における住民避難の最適化」計測自動制御学会論文集 11(5):501 の
式(1)〜(4)（浜田稔「火災の延焼速度について」『火災の研究』1, 35-44, 1951 を引いたもの）。

  風下 V1 = (1+0.01t)V1*（0≦t≦60分）、1.6V1*（t≧60分）
       V1* = k (a+b)(1+0.1w+0.007w^2) / (3 + 3a/8 + 8b/(1.15(5+w/2)))
  横   V2 = k (a+b)(1+0.005w^2)       / (3 + 3a/8 + 8b/(1.15(5+w/4)))
  風上 V3 = k (a+b)(1+0.002w^2)       / (3 + 3a/8 + 8b/(1.15(5+w/5)))
  k = (α+β)/(α+β/0.6)、α: 純木造、β: 防火造の建築面積比。単位 m/min
  a: 家屋幅[m]、b: 隣棟間隔[m]、w: 風速[m/s]、t: 出火後の時間[min]

等時延焼線は風下側が半軸 (S1, S2)、風上側が (S3, S2) の半楕円（藤田の式(5)）。火元は楕円の中心に
あるので、寺田の「火元から外郭への接線の角」は決まらない。形の数は S2/S1 で、t≧60分では
S2/S1 → V2/(1.6 V1*) に近づく。比較のため 2·atan(S2/S1) も出す。
"""
import math


def _den(a, b, D):
    return 3 + 3 * a / 8 + 8 * b / (1.15 * D)


def v1_star(w, a=8.0, b=4.0, k=1.0):
    return k * (a + b) * (1 + 0.1 * w + 0.007 * w * w) / _den(a, b, 5 + w / 2)


def v2(w, a=8.0, b=4.0, k=1.0):
    return k * (a + b) * (1 + 0.005 * w * w) / _den(a, b, 5 + w / 4)


def v3(w, a=8.0, b=4.0, k=1.0):
    return k * (a + b) * (1 + 0.002 * w * w) / _den(a, b, 5 + w / 5)


def s1(t, w, **kw):
    """風下の延焼距離 [m]（V1 を時間で積分）"""
    v = v1_star(w, **kw)
    if t <= 60:
        return v * (t + 0.005 * t * t)
    return v * (60 + 0.005 * 3600) + 1.6 * v * (t - 60)


if __name__ == "__main__":
    for a, b in ((8, 4), (8, 2), (10, 6)):
        print(f"a={a} b={b}（純木造のみ k=1）")
        print("  w[m/s]  V1*  1.6V1*  V2   V3 [m/h]   S1(4h)[km]  S2/S1(4h)  2atan(S2/S1)")
        for w in (0, 5, 10, 15, 20, 24, 30, 39):
            t = 240
            S1 = s1(t, w, a=a, b=b)
            S2 = v2(w, a=a, b=b) * t
            print(f"  {w:5.1f} {60*v1_star(w,a=a,b=b):5.0f} {96*v1_star(w,a=a,b=b):6.0f} {60*v2(w,a=a,b=b):4.0f} {60*v3(w,a=a,b=b):4.0f}"
                  f"   {S1/1000:8.2f}   {S2/S1:7.3f}   {2*math.degrees(math.atan(S2/S1)):6.1f}")
